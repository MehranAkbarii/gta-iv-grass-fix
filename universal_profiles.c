DWORD gu_universal_profile_count(void)
{
    return sizeof(g_profiles) / sizeof(g_profiles[0]);
}

const struct GuUniversalExecutableProfile *
gu_universal_profile_by_identity(DWORD identity_id)
{
    DWORD index;
    for (index = 0u; index < gu_universal_profile_count(); ++index) {
        if (g_profiles[index].identity_id == identity_id) {
            return &g_profiles[index];
        }
    }
    return NULL;
}

